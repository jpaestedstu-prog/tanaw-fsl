/* =========================================================================
   Tanaw — Contributor Studio (#/studio)
   For Deaf FSL signers, Deaf reviewers and qualified FSL educators:
     1. attach verified demonstrations (stored on this device, IndexedDB)
     2. manage on-device media
     3. add custom vocabulary
     4. share class packs as files (works offline, no server)
     5. generate media-manifest.js to publish clips permanently
     6. pipeline-test images (clearly labeled "not a sign")
   While demonstrations are switched off (core/config.js) only 3 and 4 are
   offered, as "Class vocabulary": words only, and packs carry no media.
   ========================================================================= */
(function () {
  'use strict';

  const T = window.Tanaw;
  const U = T.util;
  const { html } = U;
  const C = T.components;
  const V = (T.views = T.views || {});

  const PACK_FORMAT = 'tanaw-class-pack';
  const MAX_FILE = 200 * 1024 * 1024;

  const STANDARD = [
    'Recorded by a Deaf FSL signer, or by a qualified FSL educator.',
    'Reviewed by a qualified FSL educator or Deaf community reviewer who confirms it shows the FSL sign for the entry.',
    'The signer gave informed consent for the clip to be used to teach FSL.',
    'The region or community variant is noted, because FSL varies across the Philippines.',
    'Signs from other sign languages are never substituted for FSL.',
  ];

  function signOptions(selected) {
    return html`${T.data.allCategories().map((c) => html`
      <optgroup label="${c.label}">
        ${T.data.signsIn(c.id).map((s) => {
          const st = T.media.describe(s.id).status;
          const tag = st === 'verified' ? ' — verified' : st === 'local' ? ' — has local clip' : st === 'test' ? ' — test media' : '';
          return html`<option value="${s.id}" ${s.id === selected ? U.raw('selected') : ''}>${C.signLabel(s)}${s.fil && s.fil !== s.en ? ` · ${s.fil}` : ''}${tag}</option>`;
        })}
      </optgroup>`)}`;
  }

  function manifestEntry(rec) {
    const m = rec.meta || {};
    const ext = U.extensionForMime(rec.mime);
    const entry = {
      type: rec.kind,
      src: `assets/media/signs/${rec.signId}.${ext}`,
      signer: m.signer || '',
      signerIsDeaf: !!m.signerIsDeaf,
      verifiedBy: m.verifiedBy || '',
    };
    if (m.verifierRole) entry.verifierRole = m.verifierRole;
    if (m.region) entry.region = m.region;
    if (m.recorded) entry.recorded = m.recorded;
    entry.consent = m.consent || (m.consentConfirmed ? `Consent confirmed in Tanaw Contributor Studio on ${U.dateKey(new Date(rec.addedAt))}` : '');
    if (m.license) entry.license = m.license;
    if (m.description) entry.description = m.description;
    return entry;
  }

  function manifestFile(localRecords) {
    const merged = Object.assign({}, T.data.mediaManifest || {});
    localRecords.forEach((r) => { merged[r.signId] = manifestEntry(r); });
    return `/* =========================================================================
   Tanaw — VERIFIED MEDIA MANIFEST
   Generated by the Contributor Studio on ${new Date().toISOString().slice(0, 10)}.
   Copy each media file into assets/media/signs/ using the file names below.
   Only include clips recorded by Deaf FSL signers / qualified FSL educators,
   reviewed by a qualified verifier, with the signer's consent.
   ========================================================================= */
(function () {
  'use strict';

  const T = (window.Tanaw = window.Tanaw || {});
  const D = (T.data = T.data || {});

  D.mediaManifest = ${JSON.stringify(merged, null, 2).replace(/\n/g, '\n  ')};
})();
`;
  }

  /** Custom vocabulary + class packs: offered with or without demonstrations. */
  function vocabularyCards(demos) {
    return html`
      <section class="card studio-card" aria-labelledby="h-custom">
        <h2 class="section__title section__title--sm" id="h-custom">${T.icon('sparkles')}<span>${demos ? 'Custom vocabulary' : 'Add words'}</span></h2>
        <p>Add entries your class needs — local place names, school terms or names of people. They appear in Vocabulary under “Added on this device”.</p>
        <form class="studio-form" data-custom-form>
          <div class="form-grid">
            <div><label class="field__label" for="cu-en">English gloss <span class="req">*</span></label><input class="input" id="cu-en" maxlength="80" required></div>
            <div><label class="field__label" for="cu-fil">Filipino gloss</label><input class="input" id="cu-fil" maxlength="80" lang="fil"></div>
            <div class="form-grid__wide"><label class="field__label" for="cu-note">Note (optional)</label><input class="input" id="cu-note" maxlength="200" placeholder="Context about the word — not instructions for signing"></div>
          </div>
          <div class="btn-row"><button type="submit" class="btn btn--secondary">${T.icon('plus')}<span>Add entry</span></button></div>
        </form>
        <div data-custom-list></div>
      </section>

      <section class="card studio-card" aria-labelledby="h-packs">
        <h2 class="section__title section__title--sm" id="h-packs">${T.icon('package')}<span>Class packs</span></h2>
        <p>${demos
          ? 'Share your custom vocabulary and on-device clips as one file — by USB, messaging app or shared drive. Learners import it here, even offline.'
          : 'Share your class words as one small file — by USB, messaging app or shared drive. Learners import it on this page, even offline.'}</p>
        <form class="studio-form" data-pack-form>
          <div class="form-grid">
            <div><label class="field__label" for="pk-title">Pack title</label><input class="input" id="pk-title" maxlength="80" value="FSL class pack"></div>
            <div><label class="field__label" for="pk-author">Teacher or class</label><input class="input" id="pk-author" maxlength="80"></div>
            ${demos ? html`<div class="form-grid__wide"><label class="check"><input type="checkbox" id="pk-media" checked><span class="check__box" aria-hidden="true">${T.icon('check')}</span><span class="check__text">Include media files <span class="muted" data-pack-size></span></span></label></div>` : ''}
          </div>
          <div class="btn-row">
            <button type="submit" class="btn btn--primary">${T.icon('download')}<span>Export class pack</span></button>
            <label class="btn btn--secondary file-btn">${T.icon('upload')}<span>Import class pack</span><input type="file" accept="application/json,.json" class="visually-hidden" data-pack-import></label>
          </div>
          <p class="field__hint">${demos ? 'Test media is never included in packs.' : 'Packs contain words only — no images or video.'}</p>
        </form>
      </section>`;
  }

  V.studio = {
    title: () => (T.config.demonstrations ? 'Contributor Studio' : 'Class vocabulary'),
    station: 'studio',
    render(el, params, query, { signal }) {
      const demos = T.config.demonstrations;
      const available = T.media.isAvailable();
      const reason = T.media.initError();
      let previewURL = null;

      el.innerHTML = String(html`
        <div class="container page studio">
          ${demos ? C.pageHead({
            eyebrow: 'Contributor Studio', icon: 'studio',
            title: 'Bring verified FSL into Tanaw',
            lead: 'For Deaf FSL signers, Deaf reviewers and qualified FSL educators. Attach demonstrations with a full verification record, share them with a class as a file, and publish them permanently — no server, no account, no upload.',
          }) : C.pageHead({
            eyebrow: 'For teachers', icon: 'studio',
            title: 'Class vocabulary',
            lead: 'Add the words your class needs — local place names, school terms, names of people — and share them with your learners as a file. No server, no account, no upload.',
          })}

          ${available || !demos ? '' : C.notice('warn', 'alert', html`<p><strong>On-device media storage is unavailable in this browser.</strong> ${reason ? reason.message : ''} Custom vocabulary still works. For media, try a recent Chrome or Edge, or run Tanaw from a local server (see the README).</p>`)}

          <div class="studio-grid">
            ${!demos ? html`
            <section class="card studio-card studio-card--wide" aria-labelledby="h-words-only">
              <h2 class="section__title section__title--sm" id="h-words-only">${T.icon('shield')}<span>Words only, for now</span></h2>
              <p>Tanaw does not store or show videos of signs. ${T.config.hand3d ? 'Its experimental 3D hand shows the manual alphabet and handshapes only, and has not been validated by Deaf FSL experts. ' : ''}You teach the signs in class. Learners use the word list to mark each word “I can sign this”, review it and practice in the mirror.</p>
              <p><a href="#/about">How Tanaw handles sign content</a></p>
            </section>` : html`
            <section class="card studio-card studio-card--wide" aria-labelledby="h-standard">
              <h2 class="section__title section__title--sm" id="h-standard">${T.icon('shield')}<span>Verification standard</span></h2>
              <p>Tanaw shows a demonstration as <strong>verified</strong> only when it meets all of these:</p>
              <ul class="checklist checklist--cols">${STANDARD.map((s) => html`<li>${s}</li>`)}</ul>
              <p class="field__hint">${T.icon('info')}<span>Clips you attach here appear as <strong>On this device</strong> with the details you enter. Decisions about what is shown as FSL belong to Deaf signers and reviewers. They become <strong>Verified</strong> for everyone only when a project maintainer adds them to the media manifest (see "Publish" below).</span></p>
            </section>

            <section class="card studio-card studio-card--wide" aria-labelledby="h-attach">
              <h2 class="section__title section__title--sm" id="h-attach">${T.icon('upload')}<span>Attach a demonstration</span></h2>
              <form class="studio-form" data-attach-form novalidate>
                <div class="form-grid">
                  <div class="form-grid__wide">
                    <label class="field__label" for="at-sign">Vocabulary entry <span class="req">*</span></label>
                    <select class="select" id="at-sign" name="sign" required ${available ? '' : U.raw('disabled')}>${signOptions(query.sign || '')}</select>
                    <p class="field__hint" data-sign-hint></p>
                  </div>
                  <div class="form-grid__wide">
                    <label class="field__label" for="at-file">Video or image file <span class="req">*</span></label>
                    <input class="input input--file" id="at-file" name="file" type="file" accept="video/*,image/png,image/jpeg,image/gif,image/webp,image/avif" required ${available ? '' : U.raw('disabled')}>
                    <div class="studio-preview" data-preview hidden></div>
                  </div>
                  <div><label class="field__label" for="at-signer">Signer’s name <span class="req">*</span></label><input class="input" id="at-signer" name="signer" maxlength="120" required></div>
                  <div class="form-grid__check"><label class="check"><input type="checkbox" name="signerIsDeaf"><span class="check__box" aria-hidden="true">${T.icon('check')}</span><span class="check__text">The signer is a Deaf FSL user</span></label></div>
                  <div><label class="field__label" for="at-verifier">Verified by <span class="req">*</span></label><input class="input" id="at-verifier" name="verifiedBy" maxlength="120" required></div>
                  <div><label class="field__label" for="at-role">Verifier’s role / organization</label><input class="input" id="at-role" name="verifierRole" maxlength="160" placeholder="e.g. FSL instructor, (school or organization)"></div>
                  <div><label class="field__label" for="at-region">Region or variant</label><input class="input" id="at-region" name="region" maxlength="120" placeholder="e.g. Metro Manila, Cebu, Davao"></div>
                  <div><label class="field__label" for="at-date">Date recorded</label><input class="input" id="at-date" name="recorded" type="date"></div>
                  <div class="form-grid__wide"><label class="field__label" for="at-desc">Written description (optional, by the verifier)</label><textarea class="textarea" id="at-desc" name="description" rows="2" maxlength="600"></textarea></div>
                  <div class="form-grid__wide">
                    <label class="check check--consent"><input type="checkbox" name="consent" required><span class="check__box" aria-hidden="true">${T.icon('check')}</span>
                      <span class="check__text">I confirm the signer consented to this recording being used to teach FSL, and a qualified verifier confirmed it shows the FSL sign for this entry. <span class="req">*</span></span></label>
                  </div>
                </div>
                <p class="form-error" data-attach-error role="alert"></p>
                <div class="btn-row">
                  <button type="submit" class="btn btn--primary" ${available ? '' : U.raw('disabled')}>${T.icon('device')}<span>Save to this device</span></button>
                  <span class="field__hint">${T.icon('lock')}<span>Stored in this browser only.</span></span>
                </div>
              </form>
            </section>

            <section class="card studio-card studio-card--wide" aria-labelledby="h-media">
              <h2 class="section__title section__title--sm" id="h-media">${T.icon('film')}<span>Media on this device</span></h2>
              <div data-media-table></div>
            </section>

            `}
            ${vocabularyCards(demos)}
            ${!demos ? '' : html`
            <section class="card studio-card studio-card--wide" aria-labelledby="h-publish">
              <h2 class="section__title section__title--sm" id="h-publish">${T.icon('code')}<span>Publish permanently</span></h2>
              <ol class="steps-list">
                <li>Download each clip with <strong>Download file</strong> in the table above — it is named after its entry id.</li>
                <li>Copy the files into <code>assets/media/signs/</code> in the Tanaw project folder.</li>
                <li>Replace <code>assets/js/data/media-manifest.js</code> with the generated file below (it keeps any existing verified entries).</li>
                <li>Reload Tanaw. The clips now show as <strong>Verified</strong> for everyone using this copy.</li>
              </ol>
              <div data-publish></div>
            </section>

            <section class="card studio-card studio-card--wide studio-card--test" aria-labelledby="h-test">
              <h2 class="section__title section__title--sm" id="h-test">${T.icon('flask')}<span>Pipeline test tools</span></h2>
              <p>Want to see the quizzes, flashcards and fingerspelling drill working before real clips arrive? Generate <strong>test images</strong> for a category. Each image is plainly labeled <em>"TEST MEDIA — NOT AN FSL SIGN"</em> and shows only the written word. Entries with verified or local clips are never touched.</p>
              <div class="btn-row">
                <label class="visually-hidden" for="test-cat">Category for test images</label>
                <select class="select select--inline" id="test-cat" ${available ? '' : U.raw('disabled')}>
                  ${T.data.categories.map((c) => html`<option value="${c.id}">${c.label} (${T.data.signsIn(c.id).length})</option>`)}
                </select>
                <button type="button" class="btn btn--secondary" data-test-gen ${available ? '' : U.raw('disabled')}>${T.icon('flask')}<span>Generate test images</span></button>
                <button type="button" class="btn btn--danger-ghost" data-test-clear ${available ? '' : U.raw('disabled')}>${T.icon('trash')}<span>Remove all test media</span></button>
              </div>
              <p class="field__hint" data-test-status></p>
            </section>`}
          </div>
        </div>`);

      const form = el.querySelector('[data-attach-form]');
      const preview = el.querySelector('[data-preview]');
      const signHint = el.querySelector('[data-sign-hint]');
      const errorEl = el.querySelector('[data-attach-error]');

      /* ---------- helpers ---------- */
      function updateSignHint() {
        if (!form) return;
        const id = form.elements.sign.value;
        const d = T.media.describe(id);
        signHint.textContent = d.status === 'verified'
          ? 'This entry already has a verified clip in the manifest. The manifest clip takes priority over local media.'
          : d.status === 'local' ? 'This entry already has a clip on this device. Saving will replace it.'
            : d.status === 'test' ? 'This entry has test media. Saving will replace it with your clip.' : '';
      }

      function clearPreview() {
        if (previewURL) URL.revokeObjectURL(previewURL);
        previewURL = null;
        if (!preview) return;
        preview.hidden = true;
        preview.innerHTML = '';
      }

      function renderMediaTable() {
        const host = el.querySelector('[data-media-table]');
        if (!host) return;
        const recs = T.media.list().sort((a, b) => String(b.addedAt).localeCompare(String(a.addedAt)));
        if (!recs.length) {
          host.innerHTML = String(html`<p class="muted">No media on this device yet.</p>`);
          return;
        }
        host.innerHTML = String(html`
          <div class="table-wrap">
            <table class="table table--compact">
              <caption class="visually-hidden">Media stored on this device</caption>
              <thead><tr><th scope="col">Entry</th><th scope="col">Status</th><th scope="col">File</th><th scope="col">Signer / verifier</th><th scope="col">Added</th><th scope="col"><span class="visually-hidden">Actions</span></th></tr></thead>
              <tbody>
                ${recs.map((r) => {
                  const s = T.data.getSign(r.signId);
                  const m = r.meta || {};
                  return html`<tr data-rec="${r.signId}">
                    <td>${s ? html`<a href="#/sign/${encodeURIComponent(r.signId)}">${C.signLabel(s)}</a>` : html`<span class="muted">${r.signId} (entry missing)</span>`}</td>
                    <td>${C.statusBadge(r.source === 'test' ? 'test' : 'local', { compact: true })}</td>
                    <td>${r.kind} · ${U.formatBytes(r.size)}</td>
                    <td>${r.source === 'test' ? html`<span class="muted">—</span>` : html`${m.signer || '—'}${m.signerIsDeaf ? ' (Deaf)' : ''}<br><span class="muted">${m.verifiedBy || '—'}</span>`}</td>
                    <td>${U.formatDate(r.addedAt)}</td>
                    <td class="table__actions">
                      <button type="button" class="btn btn--ghost btn--sm" data-preview-rec>${T.icon('eye')}<span>Preview</span></button>
                      ${r.source !== 'test' ? html`<button type="button" class="btn btn--ghost btn--sm" data-download-rec>${T.icon('download')}<span>Download file</span></button>` : ''}
                      <button type="button" class="icon-btn" data-remove-rec aria-label="Remove media for ${s ? s.en : r.signId}">${T.icon('trash')}</button>
                    </td>
                  </tr>`;
                })}
              </tbody>
            </table>
          </div>`);
      }

      function renderCustomList() {
        const host = el.querySelector('[data-custom-list]');
        const list = T.store.state.custom || [];
        host.innerHTML = list.length
          ? String(html`<ul class="custom-list">${list.map((c) => html`
              <li><span><strong>${c.en}</strong>${c.fil ? html` · <span lang="fil">${c.fil}</span>` : ''}</span>
                <span class="custom-list__actions"><a class="link-btn" href="#/sign/${encodeURIComponent(c.id)}">Open</a>
                <button type="button" class="icon-btn" data-del-custom="${c.id}" aria-label="Delete ${c.en}">${T.icon('trash')}</button></span></li>`)}</ul>`)
          : String(html`<p class="muted">No custom entries yet.</p>`);
      }

      function packMedia() {
        return demos ? T.media.list().filter((r) => r.source !== 'test') : [];
      }

      function renderPackInfo() {
        if (!demos) return;
        const recs = packMedia();
        const bytes = recs.reduce((n, r) => n + (Number(r.size) || 0), 0);
        el.querySelector('[data-pack-size]').textContent = recs.length ? `(${recs.length} file${recs.length === 1 ? '' : 's'}, about ${U.formatBytes(Math.round(bytes * 1.34))})` : '(no local media yet)';
      }

      function renderPublish() {
        const host = el.querySelector('[data-publish]');
        if (!host) return;
        const recs = packMedia().filter((r) => T.data.getSign(r.signId) && !T.data.getSign(r.signId).custom);
        const customWithMedia = packMedia().filter((r) => { const s = T.data.getSign(r.signId); return s && s.custom; });
        if (!recs.length && !customWithMedia.length) {
          host.innerHTML = String(html`<p class="muted">Attach at least one demonstration to generate a manifest.</p>`);
          return;
        }
        const code = manifestFile(recs);
        host.innerHTML = String(html`
          <label class="field__label" for="manifest-code">Generated media-manifest.js</label>
          <textarea class="textarea codebox" id="manifest-code" rows="12" readonly spellcheck="false">${code}</textarea>
          <div class="btn-row">
            <button type="button" class="btn btn--secondary" data-copy-manifest>${T.icon('copy')}<span>Copy</span></button>
            <button type="button" class="btn btn--primary" data-download-manifest>${T.icon('download')}<span>Download media-manifest.js</span></button>
          </div>
          ${customWithMedia.length ? html`<p class="field__hint">${T.icon('info')}<span>${customWithMedia.length} clip${customWithMedia.length === 1 ? ' belongs' : 's belong'} to custom entries. To publish those, first add the entries to <code>assets/js/data/signs.js</code>, then regenerate.</span></p>` : ''}`);
      }

      function refreshAll() {
        renderMediaTable();
        renderCustomList();
        renderPackInfo();
        renderPublish();
        if (!form) return;
        const sel = form.elements.sign;
        const current = sel.value;
        sel.innerHTML = String(signOptions(current));
        updateSignHint();
      }

      /* ---------- attach ---------- */
      if (form) form.addEventListener('change', (e) => {
        if (e.target.name === 'sign') updateSignHint();
        if (e.target.name === 'file') {
          clearPreview();
          const file = e.target.files && e.target.files[0];
          if (!file) return;
          const kind = T.media.kindFor(file.type);
          if (!kind) { errorEl.textContent = 'Please choose a video, or a PNG, JPEG, GIF, WebP or AVIF image. (SVG images are not accepted.)'; return; }
          errorEl.textContent = file.size > MAX_FILE ? `This file is ${U.formatBytes(file.size)}. Please use a clip under ${U.formatBytes(MAX_FILE)} (short clips of a few seconds work best).` : '';
          previewURL = URL.createObjectURL(file);
          preview.hidden = false;
          preview.innerHTML = String(html`
            ${kind === 'video'
              ? html`<video src="${previewURL}" controls muted playsinline loop aria-label="Preview of selected clip"></video>`
              : html`<img src="${previewURL}" alt="Preview of selected image">`}
            <p class="field__hint">${file.name} · ${kind} · ${U.formatBytes(file.size)}</p>`);
        }
      }, { signal });

      if (form) form.addEventListener('submit', async (e) => {
        e.preventDefault();
        errorEl.textContent = '';
        const f = form.elements;
        const file = f.file.files && f.file.files[0];
        const missing = [];
        if (!f.sign.value) missing.push('an entry');
        if (!file) missing.push('a file');
        if (!f.signer.value.trim()) missing.push('the signer’s name');
        if (!f.verifiedBy.value.trim()) missing.push('the verifier’s name');
        if (!f.consent.checked) missing.push('the consent confirmation');
        if (missing.length) { errorEl.textContent = `Please add ${missing.join(', ')}.`; return; }
        if (!T.media.kindFor(file.type)) { errorEl.textContent = 'Please choose a video, or a PNG, JPEG, GIF, WebP or AVIF image. (SVG images are not accepted.)'; return; }
        if (file.size > MAX_FILE) { errorEl.textContent = `Files must be under ${U.formatBytes(MAX_FILE)}.`; return; }
        const d = T.media.describe(f.sign.value);
        if (d.status === 'local') {
          const ok = await T.ui.confirm({ title: 'Replace existing clip?', message: 'This entry already has a clip on this device. Replace it with the new one?', confirmLabel: 'Replace' });
          if (!ok) return;
        }
        try {
          await T.media.save(f.sign.value, file, {
            signer: f.signer.value,
            signerIsDeaf: f.signerIsDeaf.checked,
            verifiedBy: f.verifiedBy.value,
            verifierRole: f.verifierRole.value,
            region: f.region.value,
            recorded: f.recorded.value,
            description: f.description.value,
            consentConfirmed: true,
            fileName: file.name,
          }, 'local');
          const s = T.data.getSign(f.sign.value);
          T.ui.toast(`Saved a demonstration for "${s ? s.en : f.sign.value}".`, { icon: 'device', tone: 'success' });
          const keepSign = f.sign.value;
          form.reset();
          clearPreview();
          refreshAll();
          form.elements.sign.value = keepSign;
          updateSignHint();
        } catch (err) {
          errorEl.textContent = err && err.message ? err.message : 'Could not save this file.';
        }
      }, { signal });

      /* ---------- table actions ---------- */
      el.addEventListener('click', async (e) => {
        const row = e.target.closest('[data-rec]');
        if (row) {
          const id = row.dataset.rec;
          const rec = T.media.list().find((r) => r.signId === id);
          const sign = T.data.getSign(id) || { id, en: id, fil: '', cat: 'custom' };
          if (e.target.closest('[data-preview-rec]')) {
            T.ui.dialog({
              title: `Preview: ${C.signLabel(sign)}`,
              size: 'lg',
              body: html`${C.mediaFrame(sign, { size: 'lg', autoplay: true })}`,
              onOpen: (dlg) => C.hydrateMedia(dlg),
            });
          }
          if (e.target.closest('[data-download-rec]') && rec) {
            try {
              const blob = await T.media.getBlob(id);
              if (blob) U.download(`${id}.${U.extensionForMime(rec.mime)}`, blob);
            } catch (err) { T.ui.toast('Could not read this file.', { icon: 'alert', tone: 'danger' }); }
          }
          if (e.target.closest('[data-remove-rec]')) {
            const ok = await T.ui.confirm({ title: 'Remove this media?', message: `Remove the ${rec && rec.source === 'test' ? 'test image' : 'clip'} for "${sign.en}" from this device?`, confirmLabel: 'Remove', danger: true });
            if (!ok) return;
            await T.media.remove(id);
            refreshAll();
            T.ui.toast('Media removed.', { icon: 'trash' });
          }
        }

        const delCustom = e.target.closest('[data-del-custom]');
        if (delCustom) {
          const id = delCustom.dataset.delCustom;
          const ok = await T.ui.confirm({ title: 'Delete custom entry?', message: 'This removes the entry and any media attached to it on this device.', confirmLabel: 'Delete', danger: true });
          if (!ok) return;
          T.store.update((st) => { st.custom = (st.custom || []).filter((c) => c.id !== id); delete st.srs.added[id]; delete st.progress.selfcheck[id]; });
          if (T.media.describe(id).status !== 'pending' && T.media.isAvailable()) { try { await T.media.remove(id); } catch (err) { /* ignore */ } }
          refreshAll();
          T.ui.toast('Entry deleted.', { icon: 'trash' });
        }

        if (e.target.closest('[data-copy-manifest]')) {
          const ok = await U.copyText(el.querySelector('#manifest-code').value);
          T.ui.toast(ok ? 'Manifest copied.' : 'Select the text and copy it manually.', { icon: ok ? 'copy' : 'alert' });
        }
        if (e.target.closest('[data-download-manifest]')) {
          U.download('media-manifest.js', el.querySelector('#manifest-code').value, 'text/javascript;charset=utf-8');
        }

        if (e.target.closest('[data-test-gen]')) {
          const btn = e.target.closest('[data-test-gen]');
          const cat = el.querySelector('#test-cat').value;
          const status = el.querySelector('[data-test-status]');
          btn.disabled = true;
          status.textContent = 'Generating test images…';
          try {
            const n = await T.media.generateTestMedia(T.data.signsIn(cat));
            status.textContent = n ? `Created ${n} test image${n === 1 ? '' : 's'}. Try Practice → Quiz or Spaced review.` : 'Every entry in this category already has media.';
            refreshAll();
          } catch (err) {
            status.textContent = err && err.message ? err.message : 'Could not create test images.';
          }
          btn.disabled = false;
        }
        if (e.target.closest('[data-test-clear]')) {
          const n = await T.media.removeWhere((r) => r.source === 'test');
          el.querySelector('[data-test-status]').textContent = n ? `Removed ${n} test image${n === 1 ? '' : 's'}.` : 'There was no test media to remove.';
          refreshAll();
        }
      }, { signal });

      /* ---------- custom vocabulary ---------- */
      el.querySelector('[data-custom-form]').addEventListener('submit', (e) => {
        e.preventDefault();
        const en = el.querySelector('#cu-en').value.trim();
        const fil = el.querySelector('#cu-fil').value.trim();
        const note = el.querySelector('#cu-note').value.trim();
        if (!en) { el.querySelector('#cu-en').focus(); return; }
        const id = `custom-${U.slugify(en) || 'entry'}-${Math.random().toString(36).slice(2, 6)}`;
        T.store.update((st) => { st.custom = (st.custom || []).concat([{ id, en: en.slice(0, 80), fil: fil.slice(0, 80), note: note.slice(0, 200), createdAt: new Date().toISOString() }]); });
        e.target.reset();
        refreshAll();
        if (!form) { T.ui.toast(`Added “${en}” to your class vocabulary.`, { icon: 'sparkles' }); return; }
        T.ui.toast(`Added "${en}". Attach a demonstration above.`, { icon: 'sparkles' });
        form.elements.sign.value = id;
        updateSignHint();
      }, { signal });

      /* ---------- class packs ---------- */
      el.querySelector('[data-pack-form]').addEventListener('submit', async (e) => {
        e.preventDefault();
        const includeMedia = demos && el.querySelector('#pk-media').checked;
        const title = el.querySelector('#pk-title').value.trim() || 'FSL class pack';
        const author = el.querySelector('#pk-author').value.trim();
        const recs = includeMedia ? packMedia() : [];
        const custom = (T.store.state.custom || []).map((c) => ({ id: c.id, en: c.en, fil: c.fil || '', note: c.note || '' }));
        if (!recs.length && !custom.length) { T.ui.toast('Nothing to export yet — add vocabulary or media first.', { icon: 'info' }); return; }
        try {
          const media = [];
          for (const r of recs) {
            const blob = await T.media.getBlob(r.signId);
            if (!blob) continue;
            media.push({ signId: r.signId, kind: r.kind, mime: r.mime, meta: r.meta, data: await U.blobToDataURL(blob) });
          }
          const pack = { format: PACK_FORMAT, version: 1, createdAt: new Date().toISOString(), title, author, custom, media };
          U.download(`${U.slugify(title) || 'tanaw-pack'}.tanawpack.json`, JSON.stringify(pack), 'application/json');
          T.ui.toast(`Exported ${custom.length} entr${custom.length === 1 ? 'y' : 'ies'} and ${media.length} media file${media.length === 1 ? '' : 's'}.`, { icon: 'package' });
        } catch (err) {
          T.ui.toast('Export failed — the media may be too large for one file.', { icon: 'alert', tone: 'danger' });
        }
      }, { signal });

      el.addEventListener('change', async (e) => {
        if (!e.target.matches('[data-pack-import]')) return;
        const file = e.target.files && e.target.files[0];
        e.target.value = '';
        if (!file) return;
        let pack;
        try {
          pack = JSON.parse(await U.readFileAsText(file));
        } catch (err) {
          T.ui.toast('That file is not a valid class pack.', { icon: 'alert', tone: 'danger' });
          return;
        }
        if (!pack || pack.format !== PACK_FORMAT || !Array.isArray(pack.media) || !Array.isArray(pack.custom)) {
          T.ui.toast('That file is not a Tanaw class pack.', { icon: 'alert', tone: 'danger' });
          return;
        }
        const custom = pack.custom
          .filter((c) => c && typeof c.en === 'string' && c.en.trim())
          .map((c) => ({
            id: typeof c.id === 'string' && /^custom-[a-z0-9-]{1,70}$/.test(c.id) ? c.id : `custom-${U.slugify(c.en) || 'entry'}-${Math.random().toString(36).slice(2, 6)}`,
            en: String(c.en).slice(0, 80), fil: String(c.fil || '').slice(0, 80), note: String(c.note || '').slice(0, 200),
          }));
        const knownIds = new Set(T.data.allSigns().map((s) => s.id).concat(custom.map((c) => c.id)));
        // Without demonstrations, packs bring words only: any media in the file is left out.
        const media = !demos ? [] : pack.media.filter((m) => m && typeof m.signId === 'string' && knownIds.has(m.signId)
          && typeof m.data === 'string' && /^data:(video\/[a-z0-9.+-]+|image\/(png|jpeg|gif|webp|avif))(;[a-z0-9=.+-]+)*;base64,/i.test(m.data));
        const skipped = pack.media.length - media.length;
        const from = pack.author ? `From ${String(pack.author).slice(0, 80)}. ` : '';
        const words = `${custom.length} vocabulary entr${custom.length === 1 ? 'y' : 'ies'}`;
        const ok = await T.ui.confirm({
          title: `Import "${String(pack.title || 'class pack').slice(0, 80)}"?`,
          message: demos
            ? `${from}${words} and ${media.length} media file${media.length === 1 ? '' : 's'}${skipped ? ` (${skipped} invalid item${skipped === 1 ? '' : 's'} will be skipped)` : ''}. Media replaces any clip already on this device for the same entry. Only import packs from people you trust.`
            : `${from}${words}${skipped ? ` (the pack’s ${skipped} media file${skipped === 1 ? '' : 's'} will not be imported: this version of Tanaw does not show sign videos)` : ''}. Only import packs from people you trust.`,
          confirmLabel: 'Import',
        });
        if (!ok) return;
        let added = 0;
        T.store.update((st) => {
          const existing = new Set((st.custom || []).map((c) => c.id));
          custom.forEach((c) => { if (!existing.has(c.id)) { st.custom.push(Object.assign({ createdAt: new Date().toISOString() }, c)); added++; } });
        });
        let saved = 0;
        let failed = 0;
        if (!demos) {
          // Words only (see above).
        } else if (media.length && !T.media.isAvailable()) {
          T.ui.toast('Vocabulary imported, but this browser cannot store media.', { icon: 'alert', tone: 'danger', timeout: 6000 });
        } else {
          for (const m of media) {
            try {
              const blob = U.dataURLToBlob(m.data);
              if (blob.size > MAX_FILE) { failed++; continue; }
              await T.media.save(m.signId, blob, m.meta || {}, 'local');
              saved++;
            } catch (err) { failed++; }
          }
        }
        refreshAll();
        T.ui.toast(demos
          ? `Imported ${added} entr${added === 1 ? 'y' : 'ies'} and ${saved} media file${saved === 1 ? '' : 's'}${failed ? ` (${failed} failed)` : ''}.`
          : `Imported ${added} new entr${added === 1 ? 'y' : 'ies'}.`, { icon: 'package', tone: failed ? 'danger' : 'success', timeout: 6000 });
      }, { signal });

      T.bus.on('media:change', U.debounce(() => { if (el.querySelector('[data-media-table]')) { renderMediaTable(); renderPackInfo(); renderPublish(); } }, 100), signal);

      refreshAll();
      if (form && query.sign && T.data.getSign(query.sign)) {
        form.elements.sign.value = query.sign;
        updateSignHint();
        setTimeout(() => el.querySelector('#h-attach').scrollIntoView({ block: 'start' }), 60);
      }

      return () => clearPreview();
    },
  };
})();
